<?php
// studio/api/context.php — ИИ-помощник у выделения в AI Видео (кнопка «ИИ» в шапке редактора,
// Ctrl+Alt+Пробел). Подключается из assistant.php для запросов {mode: "text", op, custom?, extra?, kind,
// selection, document}.
//
// Текст в видеопроекте — это субтитры, тексты титров, названия и комментарии маркеров и названия клипов.
// Модель видит план всего ролика (клипы со временем, титры, субтитры, маркеры), а работает с выделенным:
// улучшает, исправляет, сокращает или переводит субтитры и титры (по одному элементу на строку, в том же
// порядке), даёт клипам и маркерам понятные названия, пишет главы, описание и названия ролика.
// Большой проект передаётся не целиком: начало, оглавление и окно вокруг выделения.

declare(strict_types=1);

/** Сколько токенов документа (≈ символов / 3,5) отдавать целиком. */
const STUDIO_CONTEXT_TOKENS = 16000;
/** Сколько символов брать по обе стороны от выделения в большом документе. */
const STUDIO_CONTEXT_WINDOW = 3000;
/** Больше этого текст документа не принимаем вовсе. */
const STUDIO_CONTEXT_MAX_CHARS = 2000000;

/** Задания операций меню. Ключи — id пунктов меню в studio.js. */
function studio_context_prompt(string $op): ?string
{
    $only = ' Верни ТОЛЬКО результат, без вступлений и пояснений.';
    $lines = ' Верни столько строк, сколько элементов в выделении, по одной на элемент и в том же порядке, без номеров, маркеров списка, таймкодов и кавычек.'
        . ' Перенос строки внутри элемента обозначен символом ⏎ — ставь его так же, а не настоящий перевод строки.';
    $p = [
        'subs_improve' => 'Улучши субтитры: живой естественный язык, верная пунктуация, без канцелярита; смысл и порядок реплик не меняй, длину сохраняй примерно ту же.' . $lines . $only,
        'subs_fix' => 'Исправь в субтитрах орфографию, пунктуацию, регистр и опечатки распознавания речи. Больше ничего не меняй.' . $lines . $only,
        'subs_short' => 'Сократи субтитры так, чтобы их успевали прочитать: не больше 15 знаков в секунду показа (длительность указана в квадратных скобках перед текстом) и не больше двух строк по 42 знака; убери повторы, слова-паразиты и лишнее, смысл сохрани.' . $lines . $only,
        'subs_lines' => 'Расставь переносы строк в субтитрах: не больше двух строк по 42 знака, переносы по смыслу (не отрывай предлог от слова). Текст не меняй.' . $lines . $only,
        'titles_improve' => 'Сделай тексты титров короче и выразительнее (как заголовки в ролике), смысл сохрани.' . $lines . $only,
        'titles_fix' => 'Исправь в текстах титров ошибки, опечатки, регистр и пунктуацию. Больше ничего не меняй.' . $lines . $only,
        'names_clear' => 'Дай элементам понятные короткие названия (2–5 слов) по их роли в ролике: вступление, интервью, перебивка, титр, музыка и т. п. Если роль не ясна из плана, сделай название аккуратнее, не выдумывая.' . $lines . $only,
        'names_fix' => 'Исправь в названиях опечатки, регистр и лишние символы (подчёркивания, номера дублей вроде _01, расширения файлов). Смысл не меняй.' . $lines . $only,
        'chapters' => 'Составь главы ролика для описания на YouTube или VK: строки вида «0:00 Название главы» по маркерам, титрам и субтитрам, по порядку времени; первая глава — 0:00. Не придумывай тем, которых нет в плане.' . $only,
        'description' => 'Напиши описание ролика для публикации (3–6 предложений) по титрам, субтитрам, маркерам и названиям клипов. Не выдумывай фактов; если данных мало — напиши общее описание и отметь [что уточнить].' . $only,
        'video_titles' => 'Предложи 5 вариантов названия ролика (до 8 слов) нумерованным списком, по содержанию проекта.' . $only,
        'hashtags' => 'Предложи 10–15 хэштегов для публикации ролика по его содержанию, одной строкой через пробел.' . $only,
        'summary' => 'Кратко опиши, что в проекте: длительность, сколько клипов и на каких дорожках, титры, субтитры, маркеры, что бросается в глаза для монтажа (ритм, переходы, звук). Маркированный список Markdown.',
    ];
    $langs = ['translate_ru' => 'русский', 'translate_en' => 'английский', 'translate_de' => 'немецкий', 'translate_es' => 'испанский', 'translate_zh' => 'китайский (упрощённый)'];
    if (isset($langs[$op])) {
        return "Переведи на {$langs[$op]} язык. Для субтитров переводи кратко, чтобы текст успевали прочитать за то же время."  . $lines . $only;
    }
    return $p[$op] ?? null;
}

/** Операции, которым без выделения нужен весь проект. */
function studio_context_whole_doc_ops(): array
{
    return ['chapters', 'description', 'video_titles', 'hashtags', 'summary'];
}

/** Документ целиком или (если велик) начало, оглавление и окно вокруг выделения. */
function studio_context_block(string $doc, string $selected): array
{
    $len = mb_strlen($doc, 'UTF-8');
    if ((int)($len / 3.5) <= STUDIO_CONTEXT_TOKENS) {
        return ['full', "=== ПЛАН РОЛИКА ЦЕЛИКОМ ===\n" . $doc . "\n=== КОНЕЦ ПЛАНА РОЛИКА ===\n"];
    }
    $anchor = (int)($len / 2);
    if ($selected !== '') {
        $probe = mb_substr($selected, 0, 200, 'UTF-8');
        $p = mb_strpos($doc, $probe, 0, 'UTF-8');
        if ($p !== false) {
            $anchor = $p + (int)(mb_strlen($selected, 'UTF-8') / 2);
        }
    }
    $start = max(0, $anchor - STUDIO_CONTEXT_WINDOW);
    $end = min($len, $anchor + STUDIO_CONTEXT_WINDOW);
    $toc = [];
    foreach (preg_split('/\R/u', $doc) ?: [] as $line) {
        $line = trim($line);
        if ($line === '' || mb_strlen($line, 'UTF-8') >= 100) {
            continue;
        }
        if (mb_strtoupper($line, 'UTF-8') === $line || !preg_match('/[.!?;:,]$/u', $line)) {
            $toc[] = '• ' . $line;
        }
        if (count($toc) >= 40) {
            break;
        }
    }
    $block = "=== РОЛИК БОЛЬШОЙ: ПОКАЗАНЫ НАЧАЛО, ОГЛАВЛЕНИЕ И ФРАГМЕНТ ВОКРУГ ВЫДЕЛЕНИЯ ===\n"
        . "--- Начало ---\n" . mb_substr($doc, 0, 800, 'UTF-8') . "\n"
        . "--- Оглавление ---\n" . implode("\n", $toc) . "\n"
        . "--- Фрагмент (символы {$start}–{$end} из {$len}) ---\n" . mb_substr($doc, $start, $end - $start, 'UTF-8') . "\n=== КОНЕЦ ===\n";
    return ['windowed', $block];
}

/**
 * Системная инструкция и сообщения для модели по запросу панели.
 * Возвращает [system, messages, contextMode]; при ошибке завершает запрос через studio_fail.
 */
function studio_context_request(array $in): array
{
    $op = is_string($in['op'] ?? null) ? trim($in['op']) : '';
    $custom = is_string($in['custom'] ?? null) ? trim(mb_substr($in['custom'], 0, 4000, 'UTF-8')) : '';
    $extra = is_string($in['extra'] ?? null) ? trim(mb_substr($in['extra'], 0, 2000, 'UTF-8')) : '';
    $selected = is_string($in['selection'] ?? null) ? $in['selection'] : '';
    $doc = is_string($in['document'] ?? null) ? $in['document'] : '';
    if (mb_strlen($doc, 'UTF-8') > STUDIO_CONTEXT_MAX_CHARS) {
        $doc = mb_substr($doc, 0, STUDIO_CONTEXT_MAX_CHARS, 'UTF-8');
    }
    $selected = mb_substr($selected, 0, 60000, 'UTF-8');

    if ($custom !== '') {
        $task = $custom;
    } else {
        $task = studio_context_prompt($op);
        if ($task === null) {
            studio_fail(400, 'Неизвестная операция: ' . $op);
        }
    }
    if ($extra !== '') {
        $task .= "\n\nДополнительное пожелание: " . $extra;
    }

    $kinds = ['caption' => 'субтитры', 'title' => 'тексты титров', 'clip' => 'названия клипов', 'marker' => 'названия маркеров', 'project' => 'проект целиком'];
    $kind = is_string($in['kind'] ?? null) && isset($kinds[$in['kind']]) ? $in['kind'] : 'project';
    $system = implode("\n", [
        'Ты — ИИ-помощник, встроенный в видеоредактор AI Видео (монтаж коротких роликов: соцсети, обучение, презентации, блоги).',
        'Видео ты не видишь и звук не слышишь: перед тобой только план ролика — клипы со временем, тексты титров, субтитры и маркеры.',
        'Работаешь с выделенным: ' . $kinds[$kind] . '. Остальной план — контекст.',
        'Отвечай без вступлений вроде «Вот субтитры:», без извинений и комментариев о себе.',
        'Сохраняй язык исходного текста, если задача — не перевод; по умолчанию пиши по-русски.',
    ]);
    [$mode, $context] = studio_context_block($doc, $selected);
    if ($selected !== '') {
        $target = "=== ВЫДЕЛЕНО ===\n" . $selected . "\n=== КОНЕЦ ВЫДЕЛЕННОГО ===\n\n"
            . 'Выполни задачу ТОЛЬКО для выделенного; план ролика выше — контекст.';
    } elseif (in_array($op, studio_context_whole_doc_ops(), true) || $custom !== '') {
        $target = 'Выделения нет: работай с проектом целиком.';
    } else {
        $target = 'Выделения нет: выполни задачу для показанного плана ролика.';
    }
    $user = ($doc !== '' ? $context . "\n" : '') . $target . "\n\n=== ЗАДАЧА ===\n" . $task;
    return [$system, [['role' => 'user', 'content' => $user]], $mode];
}
